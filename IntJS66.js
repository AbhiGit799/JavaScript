console.log("9">"16"); // true , here it will compare character by character,
// Lexicographically, "9" is greater than "1", so the result is true


console.log("8">19); // "8" is converted to 8, so 8 > 19 is false

console.log("">-1);  //empty string is converted to 0, so 0 > -1 is true

console.log("MD">16); // "MD" is converted to NaN, so NaN > 16 is false




