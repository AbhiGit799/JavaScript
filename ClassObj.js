class hello{

constructor()
{
    console.log("Constructor function");
}


    message()
    {
        console.log("Hello Everyone");
    }

    static greet()
    {
        console.log("Good Morning");
    }

}

let obj=new hello();

obj.message();

hello.greet();


/*

Types of Method

1. Constructor

constructor()
{
    console.log("Hello");

}

2. Prototype Method

message()
{
    console.log("Hello");
}

 
3. Static Method

static name()
{
    console.log("Hi");
}


*/





















